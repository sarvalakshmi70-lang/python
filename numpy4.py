import numpy as np

numbers = np.array([10, 20, 30, 40, 50])

print("Addition:")
print(numbers + 5)

print("Subtraction:")
print(numbers - 5)

print("Multiplication:")
print(numbers * 2)

print("Division:")
print(numbers / 2)

print("Greater than 25:")
print(numbers > 25)

print("Total:")
print(np.sum(numbers))

print("Average:")
print(np.mean(numbers))